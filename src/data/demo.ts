const inDays = (d: number, h = 20, m = 0) => {
  const x = new Date();
  x.setDate(x.getDate() + d);
  x.setHours(h, m, 0, 0);
  return x.toISOString();
};
const hoursAgo = (h: number) => new Date(Date.now() - h * 3_600_000).toISOString();

